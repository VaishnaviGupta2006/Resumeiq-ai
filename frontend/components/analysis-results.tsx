'use client'

import { useEffect, useState } from 'react'
import Link from 'next/link'
import {
  ArrowLeft,
  Download,
  TrendingUp,
  AlertTriangle,
  CheckCircle2,
  FileText,
  Target,
  Sparkles,
  Calendar,
  Award,
  Loader2,
} from 'lucide-react'
import { Button } from '@/components/ui/button'
import { ScoreGauge } from '@/components/score-gauge'
import { type AnalysisData, type ResumeInfo } from '@/lib/api'
import jsPDF from 'jspdf'

function toneClasses(score: number) {
  if (score >= 90) return 'bg-chart-3'
  if (score >= 70) return 'bg-chart-1'
  if (score >= 50) return 'bg-chart-2'
  return 'bg-chart-4'
}

function toneTextClasses(score: number) {
  if (score >= 90) return 'text-chart-3'
  if (score >= 70) return 'text-chart-1'
  if (score >= 50) return 'text-chart-2'
  return 'text-chart-4'
}

function getScoreLabel(score: number) {
  if (score >= 90) return 'Excellent'
  if (score >= 70) return 'Good'
  if (score >= 50) return 'Average'
  return 'Weak'
}

function getRecommendationBadge(recommendation: string) {
  const rec = recommendation.toLowerCase()
  if (rec === 'hire') return 'bg-chart-3/15 text-chart-3 border-chart-3/30'
  if (rec === 'consider') return 'bg-chart-1/15 text-chart-1 border-chart-1/30'
  return 'bg-chart-4/15 text-chart-4 border-chart-4/30'
}

function formatDate(dateString: string | null) {
  if (!dateString) return 'Unknown'
  const date = new Date(dateString)
  return date.toLocaleDateString('en-US', { 
    month: 'short', 
    day: 'numeric', 
    year: 'numeric' 
  })
}

export function AnalysisResults() {
  const [analysis, setAnalysis] = useState<AnalysisData | null>(null)
  const [resumeInfo, setResumeInfo] = useState<ResumeInfo | null>(null)
  const [loading, setLoading] = useState(true)
  const [exporting, setExporting] = useState(false)

  useEffect(() => {
    const analysisData = sessionStorage.getItem('analysisData')
    const resumeData = sessionStorage.getItem('resumeInfo')

    if (analysisData && resumeData) {
      try {
        setAnalysis(JSON.parse(analysisData))
        setResumeInfo(JSON.parse(resumeData))
      } catch (e) {
        console.error('Failed to parse analysis data:', e)
      }
    }
    setLoading(false)
  }, [])

  const handleExportPDF = async () => {
    if (!analysis || !resumeInfo) return
    
    try {
      setExporting(true)
      const doc = new jsPDF()
      const pageWidth = 210
      const pageHeight = 297
      const margin = 20
      const contentWidth = pageWidth - (margin * 2)
      const footerY = 280
      let yPos = margin

      // Helper function to check if we need a new page
      const checkPageBreak = (requiredSpace: number) => {
        if (yPos + requiredSpace > footerY) {
          doc.addPage()
          yPos = margin
        }
      }

      // Helper function to add footer
      const addFooter = () => {
        const pageCount = doc.getNumberOfPages()
        const currentDate = new Date().toLocaleDateString()
        for (let i = 1; i <= pageCount; i++) {
          doc.setPage(i)
          doc.setFontSize(9)
          doc.setTextColor(150, 150, 150)
          doc.text('Generated by ResumeIQ AI', margin, footerY)
          doc.text(`Page ${i} of ${pageCount}`, pageWidth - margin - 30, footerY)
          doc.text(currentDate, pageWidth / 2, footerY, { align: 'center' })
        }
      }

      // Helper function to draw progress bar
      const drawProgressBar = (x: number, y: number, width: number, score: number) => {
        const barHeight = 6
        const filledWidth = (score / 100) * width
        
        // Background bar
        doc.setFillColor(240, 240, 240)
        doc.rect(x, y, width, barHeight, 'F')
        
        // Filled bar with color coding
        if (score >= 80) {
          doc.setFillColor(34, 197, 94)
        } else if (score >= 60) {
          doc.setFillColor(249, 115, 22)
        } else {
          doc.setFillColor(239, 68, 68)
        }
        doc.rect(x, y, filledWidth, barHeight, 'F')
      }

      // Helper function to get score color
      const getScoreColor = (score: number) => {
        if (score >= 80) return [34, 197, 94]
        if (score >= 60) return [249, 115, 22]
        return [239, 68, 68]
      }

      // ==================== PROFESSIONAL HEADER ====================
      doc.setFontSize(22)
      doc.setTextColor(59, 130, 246)
      doc.setFont(undefined, 'bold')
      doc.text('ResumeIQ AI', margin, yPos)
      yPos += 8

      doc.setFontSize(12)
      doc.setTextColor(100, 100, 100)
      doc.setFont(undefined, 'normal')
      doc.text('AI Powered ATS Resume Analysis', margin, yPos)
      yPos += 10

      // Horizontal divider
      doc.setDrawColor(200, 200, 200)
      doc.line(margin, yPos, pageWidth - margin, yPos)
      yPos += 10

      // Filename and date
      doc.setFontSize(11)
      doc.setTextColor(60, 60, 60)
      doc.text(`Resume: ${resumeInfo.original_filename}`, margin, yPos)
      yPos += 6
      doc.text(`Analysis Date: ${new Date().toLocaleDateString()}`, margin, yPos)
      yPos += 15

      // ==================== ATS SCORE CARD ====================
      checkPageBreak(40)
      
      // Draw score card background
      doc.setFillColor(248, 250, 252)
      doc.roundedRect(margin, yPos, contentWidth, 35, 3, 3, 'F')
      
      // ATS Score
      doc.setFontSize(16)
      doc.setFont(undefined, 'bold')
      doc.setTextColor(0, 0, 0)
      doc.text(`ATS Score: ${analysis.ats_score}/100`, margin + 8, yPos + 12)
      
      // Recommendation with color coding
      const recColor = getScoreColor(analysis.ats_score)
      doc.setTextColor(recColor[0], recColor[1], recColor[2])
      doc.text(`Recommendation: ${analysis.recommendation.toUpperCase()}`, margin + 8, yPos + 22)
      
      // Overall Match
      doc.setTextColor(100, 100, 100)
      doc.setFont(undefined, 'normal')
      doc.setFontSize(10)
      const splitMatch = doc.splitTextToSize(analysis.overall_match, contentWidth - 16)
      doc.text(splitMatch, margin + 8, yPos + 30)
      
      yPos += 45

      // ==================== SUMMARY ====================
      if (analysis.summary) {
        checkPageBreak(30)
        doc.setFontSize(16)
        doc.setFont(undefined, 'bold')
        doc.setTextColor(0, 0, 0)
        doc.text('Summary', margin, yPos)
        yPos += 8
        
        doc.setFontSize(11)
        doc.setFont(undefined, 'normal')
        doc.setTextColor(80, 80, 80)
        const splitSummary = doc.splitTextToSize(analysis.summary, contentWidth)
        doc.text(splitSummary, margin, yPos)
        yPos += (splitSummary.length * 6) + 15
      }

      // ==================== CATEGORY SCORES WITH PROGRESS BARS ====================
      checkPageBreak(50)
      doc.setFontSize(16)
      doc.setFont(undefined, 'bold')
      doc.setTextColor(0, 0, 0)
      doc.text('Category Scores', margin, yPos)
      yPos += 10

      const categories = [
        { label: 'Skills', score: analysis.section_scores?.skills || 0 },
        { label: 'Experience', score: analysis.section_scores?.experience || 0 },
        { label: 'Education', score: analysis.section_scores?.education || 0 },
        { label: 'Projects', score: analysis.section_scores?.projects || 0 },
        { label: 'Keywords', score: analysis.section_scores?.keywords || 0 },
      ]

      categories.forEach((cat) => {
        checkPageBreak(15)
        doc.setFontSize(11)
        doc.setFont(undefined, 'normal')
        doc.setTextColor(60, 60, 60)
        doc.text(`${cat.label}`, margin, yPos)
        
        // Progress bar
        drawProgressBar(margin, yPos + 3, contentWidth - 40, cat.score)
        
        // Score text
        doc.setTextColor(100, 100, 100)
        doc.text(`${cat.score}%`, margin + contentWidth - 35, yPos + 3)
        yPos += 15
      })
      yPos += 10

      // ==================== TWO COLUMN: STRENGTHS vs IMPROVEMENTS ====================
      checkPageBreak(60)
      doc.setFontSize(16)
      doc.setFont(undefined, 'bold')
      doc.setTextColor(0, 0, 0)
      doc.text('Strengths & Areas for Improvement', margin, yPos)
      yPos += 10

      const colWidth = (contentWidth - 10) / 2
      let leftColY = yPos
      let rightColY = yPos

      // Left column: Strengths
      doc.setFontSize(12)
      doc.setFont(undefined, 'bold')
      doc.setTextColor(34, 197, 94)
      doc.text('Strengths', margin, leftColY)
      leftColY += 8

      doc.setFontSize(10)
      doc.setFont(undefined, 'normal')
      doc.setTextColor(80, 80, 80)
      analysis.strengths?.forEach((s, i) => {
        if (leftColY > footerY - 10) {
          doc.addPage()
          leftColY = margin
        }
        doc.text(`• ${s}`, margin, leftColY)
        leftColY += 6
      })

      // Right column: Areas for Improvement
      doc.setFontSize(12)
      doc.setFont(undefined, 'bold')
      doc.setTextColor(239, 68, 68)
      doc.text('Areas for Improvement', margin + colWidth + 10, rightColY)
      rightColY += 8

      doc.setFontSize(10)
      doc.setFont(undefined, 'normal')
      doc.setTextColor(80, 80, 80)
      analysis.weaknesses?.forEach((w, i) => {
        if (rightColY > footerY - 10) {
          doc.addPage()
          rightColY = margin
        }
        doc.text(`• ${w}`, margin + colWidth + 10, rightColY)
        rightColY += 6
      })

      yPos = Math.max(leftColY, rightColY) + 15

      // ==================== TWO COLUMN: MATCHING vs MISSING SKILLS ====================
      if (analysis.matching_skills?.length > 0 || analysis.missing_skills?.length > 0) {
        checkPageBreak(60)
        doc.setFontSize(16)
        doc.setFont(undefined, 'bold')
        doc.setTextColor(0, 0, 0)
        doc.text('Skills Comparison', margin, yPos)
        yPos += 10

        leftColY = yPos
        rightColY = yPos

        // Left column: Matching Skills
        if (analysis.matching_skills?.length > 0) {
          doc.setFontSize(12)
          doc.setFont(undefined, 'bold')
          doc.setTextColor(34, 197, 94)
          doc.text('✓ Matching Skills', margin, leftColY)
          leftColY += 8

          doc.setFontSize(10)
          doc.setFont(undefined, 'normal')
          doc.setTextColor(80, 80, 80)
          analysis.matching_skills.forEach((s) => {
            if (leftColY > footerY - 10) {
              doc.addPage()
              leftColY = margin
            }
            doc.text(`• ${s}`, margin, leftColY)
            leftColY += 6
          })
        }

        // Right column: Missing Skills
        if (analysis.missing_skills?.length > 0) {
          doc.setFontSize(12)
          doc.setFont(undefined, 'bold')
          doc.setTextColor(239, 68, 68)
          doc.text('✗ Missing Skills', margin + colWidth + 10, rightColY)
          rightColY += 8

          doc.setFontSize(10)
          doc.setFont(undefined, 'normal')
          doc.setTextColor(80, 80, 80)
          analysis.missing_skills.forEach((s) => {
            if (rightColY > footerY - 10) {
              doc.addPage()
              rightColY = margin
            }
            doc.text(`• ${s}`, margin + colWidth + 10, rightColY)
            rightColY += 6
          })
        }

        yPos = Math.max(leftColY, rightColY) + 15
      }

      // ==================== TWO COLUMN: MATCHED vs MISSING KEYWORDS ====================
      if (analysis.matched_keywords?.length > 0 || analysis.missing_keywords?.length > 0) {
        checkPageBreak(60)
        doc.setFontSize(16)
        doc.setFont(undefined, 'bold')
        doc.setTextColor(0, 0, 0)
        doc.text('Keywords Comparison', margin, yPos)
        yPos += 10

        leftColY = yPos
        rightColY = yPos

        // Left column: Matched Keywords
        if (analysis.matched_keywords?.length > 0) {
          doc.setFontSize(12)
          doc.setFont(undefined, 'bold')
          doc.setTextColor(34, 197, 94)
          doc.text('✓ Matched Keywords', margin, leftColY)
          leftColY += 8

          doc.setFontSize(10)
          doc.setFont(undefined, 'normal')
          doc.setTextColor(80, 80, 80)
          analysis.matched_keywords.forEach((k) => {
            if (leftColY > footerY - 10) {
              doc.addPage()
              leftColY = margin
            }
            doc.text(`• ${k}`, margin, leftColY)
            leftColY += 6
          })
        }

        // Right column: Missing Keywords
        if (analysis.missing_keywords?.length > 0) {
          doc.setFontSize(12)
          doc.setFont(undefined, 'bold')
          doc.setTextColor(239, 68, 68)
          doc.text('✗ Missing Keywords', margin + colWidth + 10, rightColY)
          rightColY += 8

          doc.setFontSize(10)
          doc.setFont(undefined, 'normal')
          doc.setTextColor(80, 80, 80)
          analysis.missing_keywords.forEach((k) => {
            if (rightColY > footerY - 10) {
              doc.addPage()
              rightColY = margin
            }
            doc.text(`• ${k}`, margin + colWidth + 10, rightColY)
            rightColY += 6
          })
        }

        yPos = Math.max(leftColY, rightColY) + 15
      }

      // ==================== IMPROVEMENT SUGGESTIONS BOX ====================
      if (analysis.improvement_suggestions?.length > 0) {
        checkPageBreak(80)
        
        // Draw box
        const boxHeight = Math.min(80, analysis.improvement_suggestions.length * 8 + 20)
        doc.setFillColor(248, 250, 252)
        doc.roundedRect(margin, yPos, contentWidth, boxHeight, 3, 3, 'F')
        doc.setDrawColor(200, 200, 200)
        doc.roundedRect(margin, yPos, contentWidth, boxHeight, 3, 3, 'S')
        
        doc.setFontSize(16)
        doc.setFont(undefined, 'bold')
        doc.setTextColor(0, 0, 0)
        doc.text('Recommended Improvements', margin + 8, yPos + 12)
        yPos += 22

        doc.setFontSize(11)
        doc.setFont(undefined, 'normal')
        doc.setTextColor(80, 80, 80)
        analysis.improvement_suggestions.forEach((s, i) => {
          if (yPos > margin + boxHeight - 10) {
            doc.addPage()
            yPos = margin
          }
          const splitSuggestion = doc.splitTextToSize(`${i + 1}. ${s}`, contentWidth - 16)
          doc.text(splitSuggestion, margin + 8, yPos)
          yPos += (splitSuggestion.length * 6) + 4
        })
        yPos += 15
      }

      // ==================== ADD FOOTER ====================
      addFooter()

      doc.save(`ResumeIQ_Analysis_${resumeInfo.original_filename.replace(/\.[^/.]+$/, "")}.pdf`)
    } catch (error) {
      console.error('PDF generation failed:', error)
      alert('Failed to generate PDF. Please try again.')
    } finally {
      setExporting(false)
    }
  }

  if (loading) {
    return (
      <div className="flex items-center justify-center py-20">
        <Loader2 className="size-8 animate-spin text-muted-foreground" />
      </div>
    )
  }

  if (!analysis || !resumeInfo) {
    return (
      <div className="flex flex-col items-center justify-center py-20">
        <p className="text-muted-foreground">No analysis data found. Please upload a resume first.</p>
        <Link href="/upload">
          <Button className="mt-4">Go to Upload</Button>
        </Link>
      </div>
    )
  }

  const categories = [
    { label: 'Skills', score: analysis.section_scores?.skills || 0 },
    { label: 'Experience', score: analysis.section_scores?.experience || 0 },
    { label: 'Education', score: analysis.section_scores?.education || 0 },
    { label: 'Projects', score: analysis.section_scores?.projects || 0 },
    { label: 'Keywords', score: analysis.section_scores?.keywords || 0 },
  ]

  return (
    <div className="space-y-8">
      {/* Top Section */}
      <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04),0_12px_32px_-12px_rgba(15,23,42,0.12)] sm:p-8">
        <div className="flex flex-col gap-6 lg:flex-row lg:items-start lg:justify-between">
          <div className="flex-1">
            <div className="mb-4 flex flex-wrap items-center gap-2">
              <Link href="/upload">
                <Button variant="ghost" size="sm" className="text-muted-foreground">
                  <ArrowLeft className="size-4 mr-2" />
                  Back
                </Button>
              </Link>
              <Link href="/dashboard">
                <Button variant="ghost" size="sm" className="text-muted-foreground">
                  Dashboard
                </Button>
              </Link>
            </div>
            <div className="flex items-center gap-3">
              <div className="flex size-12 items-center justify-center rounded-xl bg-accent text-accent-foreground">
                <FileText className="size-6" />
              </div>
              <div>
                <h1 className="text-xl font-semibold text-foreground sm:text-2xl">
                  {resumeInfo.original_filename}
                </h1>
                <p className="text-sm text-muted-foreground">
                  Uploaded on {formatDate(new Date().toISOString())}
                </p>
              </div>
            </div>
          </div>
          <div className="flex flex-col items-end gap-4">
            <div className="flex items-center gap-3">
              <div className="text-right">
                <p className="text-sm text-muted-foreground">Recommendation</p>
                <span className={`inline-flex items-center gap-1.5 rounded-full border px-3 py-1 text-sm font-medium capitalize ${getRecommendationBadge(analysis.recommendation)}`}>
                  <Award className="size-3.5" />
                  {analysis.recommendation}
                </span>
              </div>
            </div>
            <Button 
              size="lg" 
              className="rounded-full px-6 shadow-sm"
              onClick={handleExportPDF}
              disabled={exporting}
            >
              {exporting ? (
                <>
                  <Loader2 className="size-4 mr-2 animate-spin" />
                  Generating...
                </>
              ) : (
                <>
                  <Download className="size-4 mr-2" />
                  Export PDF
                </>
              )}
            </Button>
          </div>
        </div>
      </div>

      {/* Score Section */}
      <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04),0_12px_32px_-12px_rgba(15,23,42,0.12)] sm:p-8">
        <div className="flex flex-col items-center gap-6 text-center">
          <ScoreGauge score={analysis.ats_score} />
          <div>
            <h2 className="text-3xl font-bold text-foreground">
              {analysis.ats_score}/100
            </h2>
            <p className={`mt-1 text-lg font-semibold ${toneTextClasses(analysis.ats_score)}`}>
              {getScoreLabel(analysis.ats_score)}
            </p>
          </div>
          <p className="max-w-md text-muted-foreground">
            {analysis.overall_match}
          </p>
        </div>
      </div>

      {/* Category Scores */}
      <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
        <h2 className="mb-6 text-lg font-semibold text-foreground">Category Scores</h2>
        <div className="space-y-6">
          {categories.map((c) => (
            <div key={c.label}>
              <div className="mb-2 flex items-center justify-between">
                <span className="font-medium text-foreground">{c.label}</span>
                <span className={`font-semibold tabular-nums ${toneTextClasses(c.score)}`}>
                  {c.score}/100
                </span>
              </div>
              <div className="h-3 w-full overflow-hidden rounded-full bg-muted">
                <div
                  className={`h-full rounded-full transition-all duration-500 ${toneClasses(c.score)}`}
                  style={{ width: `${Math.max(0, Math.min(100, c.score))}%` }}
                />
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Resume Summary */}
      {analysis.summary && (
        <div className="rounded-3xl border border-border bg-accent/50 p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <div className="mb-4 flex items-center gap-2">
            <Sparkles className="size-5 text-primary" />
            <h2 className="text-lg font-semibold text-foreground">Resume Summary</h2>
          </div>
          <p className="text-muted-foreground leading-relaxed">
            {analysis.summary}
          </p>
        </div>
      )}

      {/* Strengths */}
      <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
        <div className="mb-6 flex items-center gap-2">
          <div className="flex size-8 items-center justify-center rounded-lg bg-chart-3/15 text-chart-3">
            <CheckCircle2 className="size-5" />
          </div>
          <h2 className="text-lg font-semibold text-foreground">Strengths</h2>
        </div>
        <div className="grid gap-3 sm:grid-cols-2">
          {analysis.strengths?.map((s, i) => (
            <div key={i} className="flex items-start gap-3 rounded-xl bg-chart-3/5 p-4">
              <CheckCircle2 className="mt-0.5 size-5 shrink-0 text-chart-3" />
              <span className="text-sm text-foreground">{s}</span>
            </div>
          ))}
        </div>
      </div>

      {/* Weaknesses */}
      {analysis.weaknesses && analysis.weaknesses.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <div className="mb-6 flex items-center gap-2">
            <div className="flex size-8 items-center justify-center rounded-lg bg-chart-4/15 text-chart-4">
              <AlertTriangle className="size-5" />
            </div>
            <h2 className="text-lg font-semibold text-foreground">Areas for Improvement</h2>
          </div>
          <div className="grid gap-3 sm:grid-cols-2">
            {analysis.weaknesses.map((w, i) => (
              <div key={i} className="flex items-start gap-3 rounded-xl bg-chart-4/5 p-4">
                <AlertTriangle className="mt-0.5 size-5 shrink-0 text-chart-4" />
                <span className="text-sm text-foreground">{w}</span>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Matching Skills */}
      {analysis.matching_skills && analysis.matching_skills.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <h2 className="mb-4 text-lg font-semibold text-foreground">Matching Skills</h2>
          <div className="flex flex-wrap gap-2">
            {analysis.matching_skills.map((skill, i) => (
              <span
                key={i}
                className="inline-flex items-center gap-1.5 rounded-full bg-chart-3/15 px-3 py-1.5 text-sm font-medium text-chart-3"
              >
                <CheckCircle2 className="size-3.5" />
                {skill}
              </span>
            ))}
          </div>
        </div>
      )}

      {/* Missing Skills */}
      {analysis.missing_skills && analysis.missing_skills.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <h2 className="mb-4 text-lg font-semibold text-foreground">Missing Skills</h2>
          <div className="flex flex-wrap gap-2">
            {analysis.missing_skills.map((skill, i) => (
              <span
                key={i}
                className="inline-flex items-center gap-1.5 rounded-full bg-chart-4/15 px-3 py-1.5 text-sm font-medium text-chart-4"
              >
                <AlertTriangle className="size-3.5" />
                {skill}
              </span>
            ))}
          </div>
        </div>
      )}

      {/* Matched Keywords */}
      {analysis.matched_keywords && analysis.matched_keywords.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <h2 className="mb-4 text-lg font-semibold text-foreground">Matched Keywords</h2>
          <div className="flex flex-wrap gap-2">
            {analysis.matched_keywords.map((keyword, i) => (
              <span
                key={i}
                className="rounded-lg bg-chart-3/10 px-3 py-1.5 text-sm font-medium text-chart-3"
              >
                {keyword}
              </span>
            ))}
          </div>
        </div>
      )}

      {/* Missing Keywords */}
      {analysis.missing_keywords && analysis.missing_keywords.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <h2 className="mb-4 text-lg font-semibold text-foreground">Missing Keywords</h2>
          <div className="flex flex-wrap gap-2">
            {analysis.missing_keywords.map((keyword, i) => (
              <span
                key={i}
                className="rounded-lg bg-chart-4/10 px-3 py-1.5 text-sm font-medium text-chart-4"
              >
                {keyword}
              </span>
            ))}
          </div>
        </div>
      )}

      {/* Improvement Suggestions */}
      {analysis.improvement_suggestions && analysis.improvement_suggestions.length > 0 && (
        <div className="rounded-3xl border border-border bg-card p-6 shadow-[0_1px_2px_rgba(15,23,42,0.04)] sm:p-8">
          <div className="mb-6 flex items-center gap-2">
            <div className="flex size-8 items-center justify-center rounded-lg bg-primary/15 text-primary">
              <TrendingUp className="size-5" />
            </div>
            <h2 className="text-lg font-semibold text-foreground">Improvement Suggestions</h2>
          </div>
          <div className="space-y-4">
            {analysis.improvement_suggestions.map((suggestion, i) => (
              <div key={i} className="flex gap-4 rounded-xl bg-accent p-4">
                <span className="flex size-8 shrink-0 items-center justify-center rounded-full bg-primary text-sm font-semibold text-primary-foreground">
                  {i + 1}
                </span>
                <p className="text-sm text-foreground">{suggestion}</p>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* CTA */}
      <div className="flex flex-col items-center justify-between gap-4 rounded-3xl border border-primary/20 bg-accent/60 p-6 text-center sm:flex-row sm:text-left">
        <div className="flex items-center gap-3">
          <span className="flex size-10 items-center justify-center rounded-xl bg-primary text-primary-foreground">
            <Sparkles className="size-5" />
          </span>
          <div>
            <p className="text-sm font-semibold text-foreground">
              Let AI rewrite your weak sections
            </p>
            <p className="text-sm text-accent-foreground">
              Generate optimized bullet points tailored to your target role.
            </p>
          </div>
        </div>
        <Button size="lg" className="rounded-full px-5 shadow-sm">
          Rewrite with AI
        </Button>
      </div>
    </div>
  )
}
